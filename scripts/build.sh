#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."
sdk_version="$(xcrun --sdk macosx --show-sdk-version)"
if (( ${sdk_version%%.*} < 26 )); then
  printf '%s\n' 'Docling Mac requires Xcode 26+ with the macOS 26+ SDK. The app still runs on macOS 14+.' >&2
  exit 1
fi
if ! xcrun --find actool >/dev/null 2>&1; then
  printf '%s\n' 'Select Xcode 26+ with DEVELOPER_DIR to compile the layered app icon; Command Line Tools alone are insufficient.' >&2
  exit 1
fi
# The Swift Build engine in some SDKs writes the deployment target as the linked
# SDK version, which opts standard controls out of Liquid Glass. Use SwiftPM's
# native driver and verify the actual Mach-O metadata before packaging.
swift build -c release --build-system native --sdk "$(xcrun --sdk macosx --show-sdk-path)"
linked_sdk="$(xcrun vtool -show-build .build/release/DoclingMac | awk '$1 == "sdk" { print $2 }')"
if [[ -z "$linked_sdk" ]] || (( ${linked_sdk%%.*} < 26 )); then
  printf '%s\n' "Expected a macOS 26+ linked SDK for Liquid Glass, got: $linked_sdk" >&2
  exit 1
fi
app="$PWD/dist/Docling Mac.app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources/Backend"
# Old development runs may have generated bytecode in this build artifact.
if [[ -d "$app/Contents/Resources/Backend/__pycache__" ]]; then
  rm -f "$app/Contents/Resources/Backend/__pycache__/"*.pyc
  rmdir "$app/Contents/Resources/Backend/__pycache__"
fi
cp .build/release/DoclingMac "$app/Contents/MacOS/DoclingMac"
strip -S "$app/Contents/MacOS/DoclingMac"
cp Backend/worker.py Backend/result_cache.py Backend/models.py Backend/runtime.json Backend/pyproject.toml Backend/uv.lock "$app/Contents/Resources/Backend/"
cp Info.plist "$app/Contents/Info.plist"
cp LICENSE THIRD_PARTY_NOTICES.md "$app/Contents/Resources/"
# Keep the original .icns for macOS 14/15 and let macOS 26+ use the layered icon.
mkdir -p .build/icon-assets
xcrun actool Assets/AppIcon.icon --compile .build/icon-assets --platform macosx \
  --minimum-deployment-target 14.0 --app-icon AppIcon \
  --output-partial-info-plist .build/icon-info.plist --output-format human-readable-text --notices --warnings
cp .build/icon-assets/Assets.car "$app/Contents/Resources/"
/usr/libexec/PlistBuddy -c 'Merge .build/icon-info.plist' "$app/Contents/Info.plist"
swift scripts/make-icon.swift .build/AppIcon.iconset
iconutil -c icns .build/AppIcon.iconset -o "$app/Contents/Resources/AppIcon.icns"
codesign --force --deep --sign - "$app"
printf '%s\n' "$app"
